"""---
# ***Fase 5: Evaluation***

---

> Evaluasi Model dengan Metrik Relevan
"""

def evaluate_model_full(model, X_test, y_test, model_name):
    y_pred = model.predict(X_test)

    precision = precision_score(y_test, y_pred)
    recall = recall_score(y_test, y_pred)
    cm = confusion_matrix(y_test, y_pred)
    TN, FP, FN, TP = cm.ravel()

    print(f"\n--- Metrik {model_name} ---")

    metrics_data = {
        'Metrik': ['Precision', 'Recall'],
        'Skor': [f"{precision:.4f}", f"{recall:.4f}"]
    }
    display(pd.DataFrame(metrics_data))

    print("\nAnalisis Confusion Matrix:")
    cm_df = pd.DataFrame(cm, columns=['Predicted No', 'Predicted Yes'], index=['Actual No', 'Actual Yes'])
    display(cm_df)

    print(f"\nInterpretasi Komponen CM:")
    print(f"True Positives (TP): {TP}")
    print(f"False Positives (FP): {FP} (Nasabah Non-Potensial yang SALAH diprediksi 'Yes')")
    print(f"False Negatives (FN): {FN} (Nasabah Potensial yang TERLEWAT)")

    plt.figure(figsize=(4, 3))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', cbar=False,
                xticklabels=['No', 'Yes'],
                yticklabels=['No', 'Yes'])
    plt.title(f'CM - {model_name}')
    plt.xlabel('Predicted Label')
    plt.ylabel('True Label')
    plt.show()

print("\n--- Step 5.1: Hasil Metrik ---")
evaluate_model_full(log_model, X_test, y_test, "Logistic Regression (Baseline)")

